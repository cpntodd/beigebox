void BuildManager::DoBuild()
{
    if (buildRunning_) return;

    if (!ValidateBuild())
    {
        buildProgress_ = 0.0f;
        buildStatus_ = "Build failed — see log";
        return;
    }

    buildRunning_ = true;
    buildProgress_ = 0.0f;
    currentStep_ = 0;
    ClearLog();
    Log("Starting build v" + std::string(versionBuf_) + "...");

    std::string dest(outputPath_);

    // Step 1: Clean output directory
    currentStep_++;
    buildProgress_ = static_cast<float>(currentStep_) / totalSteps_;
    buildStatus_ = "Cleaning output directory...";
    Log("  [1/" + std::to_string(totalSteps_) + "] Cleaning " + dest + "...");
    std::string rmCmd = "rm -rf \"" + dest + "\" && mkdir -p \"" + dest + "\"";
    system(rmCmd.c_str());

    // Step 2: Create subdirectories
    currentStep_++;
    buildProgress_ = static_cast<float>(currentStep_) / totalSteps_;
    buildStatus_ = "Creating directory structure...";
    Log("  [2/" + std::to_string(totalSteps_) + "] Creating subdirectories...");
    const char* subdirs[] = {"assets", "assets/sprites", "assets/sounds",
        "assets/music", "assets/scripts", "data", "data/units",
        "data/buildings", "data/heroes", "data/factions",
        "scenarios", "ui", "ui/menus"};
    for (auto& sd : subdirs)
    {
        std::string full = dest + "/" + sd;
        mkdir(full.c_str(), 0755);
    }

    // Step 3: Copy runtime
    currentStep_++;
    buildProgress_ = static_cast<float>(currentStep_) / totalSteps_;
    buildStatus_ = "Copying runtime executable...";
    Log("  [3/" + std::to_string(totalSteps_) + "] Copying runtime...");
    std::string srcExe = rootPath_ + "/build/engine/beigebox_runtime";
    std::string dstExe = dest + "/beigebox_runtime";
    if (CopyFile(srcExe, dstExe))
    {
        chmod(dstExe.c_str(), 0755);
        Log("    beigebox_runtime ✓");
    }
    else
        Log("    ERROR: Failed to copy runtime");

    // Step 4: Copy assets
    currentStep_++;
    buildProgress_ = static_cast<float>(currentStep_) / totalSteps_;
    buildStatus_ = "Copying assets...";
    Log("  [4/" + std::to_string(totalSteps_) + "] Copying assets...");
    auto copyAssetDir = [&](const char* sub) {
        std::string src = rootPath_ + "/" + sub;
        std::string dst = dest + "/" + sub;
        CopyDir(src, dst);
        Log("    " + std::string(sub) + " ✓");
    };
    copyAssetDir("assets/sprites");
    copyAssetDir("assets/sounds");
    copyAssetDir("assets/music");
    copyAssetDir("assets/scripts");

    // Step 5: Copy data
    currentStep_++;
    buildProgress_ = static_cast<float>(currentStep_) / totalSteps_;
    buildStatus_ = "Copying game data...";
    Log("  [5/" + std::to_string(totalSteps_) + "] Copying game data...");
    copyAssetDir("data/units");
    copyAssetDir("data/buildings");
    copyAssetDir("data/heroes");
    copyAssetDir("data/factions");

    // Step 6: Copy scenarios & UI
    currentStep_++;
    buildProgress_ = static_cast<float>(currentStep_) / totalSteps_;
    buildStatus_ = "Copying scenarios and UI...";
    Log("  [6/" + std::to_string(totalSteps_) + "] Copying scenarios & UI...");
    copyAssetDir("scenarios");
    copyAssetDir("ui/menus");

    // Step 7: Generate launcher + version
    currentStep_++;
    buildProgress_ = static_cast<float>(currentStep_) / totalSteps_;
    buildStatus_ = "Generating launcher...";
    Log("  [7/" + std::to_string(totalSteps_) + "] Generating launch.sh...");
    std::string script = GenerateLaunchScript();
    std::string lp = dest + "/launch.sh";
    std::ofstream lf(lp);
    lf << script; lf.close();
    chmod(lp.c_str(), 0755);
    Log("    launch.sh ✓");

    std::string vp = dest + "/VERSION";
    std::ofstream vf(vp);
    vf << versionBuf_ << "\n"; vf.close();
    Log("    VERSION ✓");

    // Step 8: Package .tar.gz
    currentStep_++;
    buildProgress_ = static_cast<float>(currentStep_) / totalSteps_;
    buildStatus_ = "Packaging...";
    Log("  [8/" + std::to_string(totalSteps_) + "] Packaging...");

    if (packageTarGz_)
    {
        std::string tgzName = std::string(outputPath_) + ".tar.gz";
        std::string tarCmd = "cd \"" + std::string(outputPath_) +
            "\"/.. && tar czf \"" + tgzName + "\" \"$(basename \"" +
            std::string(outputPath_) + "\")\"";
        if (system(tarCmd.c_str()) == 0)
            Log("    " + tgzName + " ✓");
        else
            Log("    ERROR: Failed to create .tar.gz (tar not found?)");
    }
    else
    {
        Log("    Skipped (.tar.gz disabled)");
    }

    buildProgress_ = 1.0f;
    buildStatus_ = "DONE";
    Log("Build complete: " + dest);
    Log("  Run with: cd " + dest + " && ./launch.sh");
    buildRunning_ = false;
}

void BuildManager::DoPackage()
{
    // Manual re-package of existing build
    if (packageTarGz_)
    {
        std::string tgzName = std::string(outputPath_) + ".tar.gz";
        std::string tarCmd = "cd \"" + std::string(outputPath_) +
            "\"/.. && tar czf \"" + tgzName + "\" \"$(basename \"" +
            std::string(outputPath_) + "\")\"";
        if (system(tarCmd.c_str()) == 0)
            Log("Packaged: " + tgzName);
        else
            Log("ERROR: Failed to create .tar.gz");
    }
}

