void BuildManager::Draw()
{
    if (!show_) return;

    ImGui::SetNextWindowSize(ImVec2(520, 500), ImGuiCond_FirstUseEver);
    ImGui::Begin("Build & Export Manager", &show_);

    // ── Configuration ────────────────────────────────────────
    if (ImGui::CollapsingHeader("Configuration", ImGuiTreeNodeFlags_DefaultOpen))
    {
        ImGui::InputText("Output Path", outputPath_, sizeof(outputPath_));
        ImGui::SameLine();
        if (ImGui::Button("...##browseOutput", ImVec2(30, 0)))
        {
#ifdef __linux__
            FILE* pipe = popen("zenity --file-selection --directory 2>/dev/null", "r");
            if (pipe) {
                char line[512];
                if (fgets(line, sizeof(line), pipe)) {
                    size_t len = strlen(line);
                    if (len > 0 && line[len-1] == '\n') line[len-1] = '\0';
                    strncpy(outputPath_, line, sizeof(outputPath_) - 1);
                }
                pclose(pipe);
            }
#endif
        }

        ImGui::InputText("Version", versionBuf_, sizeof(versionBuf_));

        ImGui::Checkbox("Linux (native)", &buildLinux_);
        ImGui::SameLine();
        ImGui::Checkbox("Windows (cross)", &buildWindows_);
        ImGui::SameLine();
        ImGui::Checkbox("Package .tar.gz", &packageTarGz_);

        ImGui::Separator();
        ImGui::Text("Package contents:");
        ImGui::BulletText("beigebox_runtime");
        ImGui::BulletText("assets/ (sprites, sounds, music, scripts)");
        ImGui::BulletText("data/ (units, buildings, factions)");
        ImGui::BulletText("scenarios/");
        ImGui::BulletText("ui/menus/");
        ImGui::BulletText("launch.sh");
        ImGui::BulletText("VERSION");
    }

    ImGui::Separator();

    // ── Build button ─────────────────────────────────────────
    ImGui::PushStyleVar(ImGuiStyleVar_FramePadding, ImVec2(16, 12));
    if (ImGui::Button("Build & Export", ImVec2(200, 0)))
        DoBuild();
    ImGui::PopStyleVar();

    ImGui::SameLine();
    if (ImGui::Button("Clear Log"))
        ClearLog();

    ImGui::SameLine();
    ImGui::Checkbox("Auto-scroll", &autoScroll_);

    // ── Progress ─────────────────────────────────────────────
    if (buildRunning_)
    {
        ImGui::ProgressBar(buildProgress_, ImVec2(0, 20));
        ImGui::SameLine();
        ImGui::Text("%.0f%%", buildProgress_ * 100.0f);
        ImGui::Text("%s", buildStatus_.c_str());
    }

    ImGui::Separator();

    // ── Build log ────────────────────────────────────────────
    ImGui::BeginChild("##buildLog", ImVec2(0, 0), true);

    for (auto& entry : buildLog_)
    {
        ImVec4 col(0.7f, 0.7f, 0.7f, 1.0f);
        if (entry.find("ERROR") != std::string::npos)
            col = ImVec4(1.0f, 0.3f, 0.3f, 1.0f);
        else if (entry.find("DONE") != std::string::npos ||
                 entry.find("Complete") != std::string::npos)
            col = ImVec4(0.3f, 0.9f, 0.3f, 1.0f);
        else if (entry.find("  ") == 0) // indented = detail
            col = ImVec4(0.5f, 0.5f, 0.5f, 1.0f);

        ImGui::TextColored(col, "%s", entry.c_str());
    }

    if (autoScroll_ && ImGui::GetScrollY() >= ImGui::GetScrollMaxY())
        ImGui::SetScrollHereY(1.0f);

    ImGui::EndChild();

    ImGui::End();
}

