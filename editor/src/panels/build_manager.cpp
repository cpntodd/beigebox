BuildManager::BuildManager()
{
    ClearLog();
}

void BuildManager::Log(const std::string& msg)
{
    buildLog_.push_back(msg);
    if (aiChat_) aiChat_->AppendMessage("system", "[Build] " + msg);
    SDL_Log("[Build] %s", msg.c_str());
}

void BuildManager::ClearLog()
{
    buildLog_.clear();
    buildLog_.push_back("Build Manager ready.");
}

bool BuildManager::CopyFile(const std::string& src, const std::string& dst)
{
    std::ifstream in(src, std::ios::binary);
    if (!in.good()) return false;
    std::ofstream out(dst, std::ios::binary);
    if (!out.good()) return false;
    out << in.rdbuf();
    return true;
}

bool BuildManager::CopyDir(const std::string& srcDir, const std::string& dstDir)
{
    std::string cmd = "cp -r \"" + srcDir + "\"/* \"" + dstDir + "\"/ 2>/dev/null";
    return system(cmd.c_str()) == 0;
}

std::string BuildManager::GenerateLaunchScript() const
{
    std::string script = "#!/bin/sh\n";
    script += "# M.A.D. Runtime Launcher — v" + std::string(versionBuf_) + "\n";
    script += "# Generated by M.A.D. Editor Build Manager\n\n";
    script += "cd \"$(dirname \"$0\")\"\n";
    script += "export LD_LIBRARY_PATH=\"./lib:$LD_LIBRARY_PATH\"\n";
    script += "exec ./beigebox_runtime \"$@\"\n";
    return script;
}

bool BuildManager::ValidateBuild()
{
    // Check that the runtime executable exists
    std::string exePath = rootPath_ + "/build/engine/beigebox_runtime";
    std::ifstream test(exePath);
    if (!test.good())
    {
        Log("ERROR: Runtime not found at " + exePath);
        Log("  Build the project first: cmake --build build");
        return false;
    }
    return true;
}

